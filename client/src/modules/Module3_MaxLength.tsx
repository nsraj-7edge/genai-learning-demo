function CostProjection({ tokens }: { tokens: number }) {
  const costPerCall = (tokens / 1000) * COST_PER_OUTPUT_K;
  const rows = [
    { label: 'Per call',        v: costPerCall,          fmt: (n: number) => `$${n.toFixed(5)}` },
    { label: '/hr (1 per min)', v: costPerCall * 60,     fmt: (n: number) => `$${n.toFixed(3)}` },
    { label: 'Per day',         v: costPerCall * 60 * 24, fmt: (n: number) => `$${n.toFixed(2)}` },
    { label: 'Per year',        v: costPerCall * 60 * 24 * 365, fmt: (n: number) => `$${n.toLocaleString('en', { maximumFractionDigits: 0 })}` },
  ];
  const annual = costPerCall * 60 * 24 * 365;
  return (
    <div style={{ display: 'grid', gridTemplateColumns: 'repeat(4,1fr)', gap: 6 }}>
      {rows.map(r => (
        <div key={r.label} style={{ textAlign: 'center' }}>
          <div style={{
            fontWeight: 700, fontSize: r.label === 'Per year' ? 15 : 13.5,
            fontFamily: 'var(--font-mono)',
            color: r.label === 'Per year' ? (annual > 500 ? 'var(--rose)' : annual > 50 ? 'var(--amber)' : 'var(--green)') : 'var(--text-primary)',
          }}>{r.fmt(r.v)}</div>
          <div style={{ fontSize: 10, color: 'var(--text-muted)', marginTop: 2 }}>{r.label}</div>
        </div>
      ))}
    </div>
  );
}

